// Command event types for FFI boundary

use super::types::BsonBytes;
use std::ffi::CString;
use std::os::raw::c_char;
use std::sync::atomic::{AtomicI64, Ordering};

/// Global atomic counter for generating operation IDs
/// The Rust MongoDB driver doesn't provide operationId, so we generate it ourselves
static OPERATION_ID_COUNTER: AtomicI64 = AtomicI64::new(1);

/// Command event type discriminant
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommandEventType {
    Started = 0,
    Succeeded = 1,
    Failed = 2,
}

/// Connection information matching Rust driver's ConnectionInfo
/// Simplified compared to Java's ConnectionDescription
#[repr(C)]
pub struct FfiConnectionInfo {
    /// Driver-generated connection ID
    pub connection_id: u32,
    /// Server-generated connection ID (-1 if not present)
    pub server_connection_id: i64,
    /// Whether server_connection_id is present
    pub server_connection_id_present: bool,
    /// Host address (null-terminated string)
    pub host: *const c_char,
    /// Port number
    pub port: u16,
    /// Service ID bytes (ObjectId, 12 bytes, zeroed if not present)
    pub service_id: [u8; 12],
    /// Whether service_id is present
    pub service_id_present: bool,
}

impl Default for FfiConnectionInfo {
    fn default() -> Self {
        Self {
            connection_id: 0,
            server_connection_id: -1,
            server_connection_id_present: false,
            host: std::ptr::null(),
            port: 0,
            service_id: [0u8; 12],
            service_id_present: false,
        }
    }
}

/// Union-like struct for all command event types
/// Unused fields are zeroed/null for a given event type
#[repr(C)]
pub struct FfiCommandEvent {
    /// Event type discriminant (Started=0, Succeeded=1, Failed=2)
    pub event_type: CommandEventType,
    /// Driver-generated request ID (correlates started/succeeded/failed)
    pub request_id: i32,
    /// Operation ID (generated by our FFI layer, groups related commands)
    pub operation_id: i64,
    /// Connection information
    pub connection: FfiConnectionInfo,
    /// Database name (null-terminated)
    pub database: *const c_char,
    /// Command name (null-terminated), e.g. "find", "insert"
    pub command_name: *const c_char,
    /// For Started: the command document (BSON bytes)
    pub command: BsonBytes,
    /// For Succeeded: the response document (BSON bytes)
    pub response: BsonBytes,
    /// For Succeeded/Failed: elapsed time in nanoseconds
    pub elapsed_nanos: i64,
    /// For Failed: error message (null-terminated)
    pub error_message: *const c_char,
}

impl Default for FfiCommandEvent {
    fn default() -> Self {
        Self {
            event_type: CommandEventType::Started,
            request_id: 0,
            operation_id: 0,
            connection: FfiConnectionInfo::default(),
            database: std::ptr::null(),
            command_name: std::ptr::null(),
            command: BsonBytes {
                data: std::ptr::null(),
                len: 0,
            },
            response: BsonBytes {
                data: std::ptr::null(),
                len: 0,
            },
            elapsed_nanos: 0,
            error_message: std::ptr::null(),
        }
    }
}

/// Callback function type for command events (non-nullable)
/// This is the actual function signature that Java implements
pub type CommandEventCallbackFn = extern "C" fn(event: *const FfiCommandEvent);

/// Nullable callback type for command events
/// Java implements this and passes to Rust during client creation
/// cbindgen should translate Option<extern "C" fn(...)> to a nullable C function pointer
pub type CommandEventCallback = Option<extern "C" fn(event: *const FfiCommandEvent)>;

/// Generate a new unique operation ID
pub fn generate_operation_id() -> i64 {
    OPERATION_ID_COUNTER.fetch_add(1, Ordering::SeqCst)
}

/// Create an EventHandler that forwards command events to the Java callback
///
/// This function creates a Rust driver EventHandler that:
/// 1. Receives CommandEvent from the Rust driver
/// 2. Converts it to FfiCommandEvent (our C-compatible struct)
/// 3. Calls the Java callback with a pointer to the FFI event
///
/// # Safety
/// The callback must remain valid for the lifetime of the EventHandler.
/// The callback is called synchronously, so any data pointed to by FfiCommandEvent
/// is only valid during the callback invocation.
/// Note: This function takes the unwrapped function type (not Option), as the caller
/// has already verified the callback is Some.
pub fn create_command_event_handler(
    callback: CommandEventCallbackFn,
) -> crate::event::EventHandler<crate::event::command::CommandEvent> {
    use crate::event::{command::CommandEvent, EventHandler};

    // Generate a shared operation ID for this handler
    // NOTE: In a real implementation, we'd want to track request_id -> operation_id mapping
    // For now, we use a simple approach where each event gets a new operation_id
    // TODO: Implement proper operation_id tracking based on request_id correlation

    EventHandler::callback(move |event: CommandEvent| {
        // Convert the Rust event to our FFI structure and invoke callback
        match &event {
            CommandEvent::Started(e) => convert_started_event(e, callback),
            CommandEvent::Succeeded(e) => convert_succeeded_event(e, callback),
            CommandEvent::Failed(e) => convert_failed_event(e, callback),
            _ => {} // Handle any future variants gracefully
        }
    })
}

/// Convert CommandStartedEvent to FfiCommandEvent and invoke callback
fn convert_started_event(
    event: &crate::event::command::CommandStartedEvent,
    callback: CommandEventCallbackFn,
) {
    // Prepare strings - these must live until after the callback returns
    let db_cstring = CString::new(event.db.as_str()).unwrap_or_default();
    let cmd_name_cstring = CString::new(event.command_name.as_str()).unwrap_or_default();
    let host_cstring = CString::new(event.connection.address.to_string()).unwrap_or_default();

    // Serialize command Document to BSON bytes
    let command_bytes: Vec<u8> = crate::bson::to_vec(&event.command).unwrap_or_default();

    // Build connection info
    let connection_info =
        build_connection_info(&event.connection, &event.service_id, &host_cstring);

    // Build the FFI event
    let ffi_event = FfiCommandEvent {
        event_type: CommandEventType::Started,
        request_id: event.request_id,
        operation_id: generate_operation_id(), // TODO: Track by request_id for correlation
        connection: connection_info,
        database: db_cstring.as_ptr(),
        command_name: cmd_name_cstring.as_ptr(),
        command: BsonBytes {
            data: command_bytes.as_ptr(),
            len: command_bytes.len(),
        },
        response: BsonBytes {
            data: std::ptr::null(),
            len: 0,
        },
        elapsed_nanos: 0,
        error_message: std::ptr::null(),
    };

    // Invoke the Java callback
    callback(&ffi_event);

    // All CStrings and Vec are dropped here after callback returns
}

/// Convert CommandSucceededEvent to FfiCommandEvent and invoke callback
/// NOTE: CommandSucceededEvent doesn't have a `db` field - we pass empty string
fn convert_succeeded_event(
    event: &crate::event::command::CommandSucceededEvent,
    callback: CommandEventCallbackFn,
) {
    // Prepare strings - NOTE: db is not available in CommandSucceededEvent
    let db_cstring = CString::new("").unwrap_or_default();
    let cmd_name_cstring = CString::new(event.command_name.as_str()).unwrap_or_default();
    let host_cstring = CString::new(event.connection.address.to_string()).unwrap_or_default();

    // Serialize reply Document to BSON bytes
    let reply_bytes: Vec<u8> = crate::bson::to_vec(&event.reply).unwrap_or_default();

    // Build connection info
    let connection_info =
        build_connection_info(&event.connection, &event.service_id, &host_cstring);

    // Build the FFI event
    let ffi_event = FfiCommandEvent {
        event_type: CommandEventType::Succeeded,
        request_id: event.request_id,
        operation_id: generate_operation_id(), // TODO: Track by request_id for correlation
        connection: connection_info,
        database: db_cstring.as_ptr(),
        command_name: cmd_name_cstring.as_ptr(),
        command: BsonBytes {
            data: std::ptr::null(),
            len: 0,
        },
        response: BsonBytes {
            data: reply_bytes.as_ptr(),
            len: reply_bytes.len(),
        },
        elapsed_nanos: event.duration.as_nanos() as i64,
        error_message: std::ptr::null(),
    };

    // Invoke the Java callback
    callback(&ffi_event);
}

