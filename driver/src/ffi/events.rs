/// Build FfiConnectionInfo from Rust driver's ConnectionInfo
fn build_connection_info(
    conn: &crate::event::command::ConnectionInfo,
    service_id: &Option<crate::bson::oid::ObjectId>,
    host_cstring: &CString,
) -> FfiConnectionInfo {
    // Parse address to get port (default to 27017 if not specified)
    let port: u16 = match &conn.address {
        crate::options::ServerAddress::Tcp { host: _, port } => port.unwrap_or(27017),
        #[allow(unreachable_patterns)]
        _ => 27017,
    };

    // Build service_id bytes
    let (service_id_bytes, service_id_present) = match service_id {
        Some(oid) => (oid.bytes(), true),
        None => ([0u8; 12], false),
    };

    FfiConnectionInfo {
        connection_id: conn.id,
        server_connection_id: conn.server_id.unwrap_or(-1),
        server_connection_id_present: conn.server_id.is_some(),
        host: host_cstring.as_ptr(),
        port,
        service_id: service_id_bytes,
        service_id_present,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering as AtomicOrdering};

    #[test]
    fn test_event_type_values() {
        assert_eq!(CommandEventType::Started as i32, 0);
        assert_eq!(CommandEventType::Succeeded as i32, 1);
        assert_eq!(CommandEventType::Failed as i32, 2);
    }

    #[test]
    fn test_connection_info_size() {
        // Ensure the struct has a stable layout
        // connection_id(4) + padding(4) + server_connection_id(8) + present(1) + padding(7)
        // + host(8) + port(2) + padding(6) + service_id(12) + present(1) + padding(3)
        // This is approximate - actual size depends on platform alignment
        let size = std::mem::size_of::<FfiConnectionInfo>();
        println!("FfiConnectionInfo size: {}", size);
        assert!(size > 0);
    }

    /// Test that command events actually fire when executing a command
    /// This test requires a MongoDB instance running on localhost:27017
    #[test]
    fn test_command_events_fire() {
        use crate::bson::doc;

        // Counter for events received
        static EVENT_COUNT: AtomicUsize = AtomicUsize::new(0);

        // Callback that increments the counter
        extern "C" fn test_callback(event: *const FfiCommandEvent) {
            if !event.is_null() {
                let e = unsafe { &*event };
                println!("Received event type: {:?}", e.event_type);
                EVENT_COUNT.fetch_add(1, AtomicOrdering::SeqCst);
            }
        }

        // Create a Tokio runtime
        let runtime = tokio::runtime::Runtime::new().expect("Failed to create runtime");

        // Build client options with event handler
        let mut options = crate::options::ClientOptions::default();
        options.hosts = vec!["localhost:27017".parse().unwrap()];
        options.command_event_handler = Some(create_command_event_handler(test_callback));

        // Create client and execute a command
        runtime.block_on(async {
            let client = crate::Client::with_options(options).expect("Failed to create client");
            let db = client.database("admin");

            // Execute a ping command - should trigger Started and Succeeded events
            let result = db.run_command(doc! { "ping": 1 }).await;
            println!("Ping result: {:?}", result);
            assert!(result.is_ok(), "Ping should succeed");
        });

        // Check that we received events
        let count = EVENT_COUNT.load(AtomicOrdering::SeqCst);
        println!("Total events received: {}", count);
        assert!(
            count >= 2,
            "Should have received at least Started and Succeeded events"
        );
    }
}
